import { SITE_URL } from '@/lib/seo'
import { breeds } from '@/lib/breeds'
import { hasArticle } from '@/lib/articles'
import { guides } from '@/lib/guides'
import { communities } from '@/lib/communities'

/**
 * /llms.txt - תקן מתפתח (llmstxt.org) שמתאר את האתר למנועי AI
 * (ChatGPT, Perplexity, Google AI Overviews). עוזר ל-GEO: מנועי
 * שפה מקבלים מפה תמציתית ומהימנה של התוכן והקישורים החשובים.
 */
export const dynamic = 'force-static'

export function GET() {
  const u = (p: string) => `${SITE_URL}${p}`

  const body = `# קהילה על ארבע

> מדריכי גזעים, כלים ומפת גינות לבעלי כלבים בישראל. מדריכי גזעים מקיפים, מדריכי אילוף וטיפול, כלים חינמיים, מדריכי ערים, מפת גינות כלבים, לוח אבד/נמצא, אימוץ ושוק יד שנייה. כל התוכן בעברית.

מידע מהימן לבעלי כלבים בישראל: בחירת גזע, אילוף, בריאות, תזונה ובטיחות (כולל נושאים ישראליים כמו חום בקיץ וזיקוקים ביום העצמאות). העצות מבוססות חיזוק חיובי; נושאים רפואיים מנוסחים כלליים עם המלצה להתייעץ עם וטרינר.

## מדריכי גזעים (${breeds.length} גזעים)
${breeds.map((b) => hasArticle(b.slug)
  ? `- [${b.name} (${b.en})](${u(`/articles/${b.slug}`)}): מדריך מלא - אופי, התאמה למשפחה, בריאות, טיפוח ואילוף`
  : `- [${b.name} (${b.en})](${u(`/breeds/${b.slug}`)}): פרופיל הגזע - אופי, גודל, התאמה למשפחה, בריאות ועלות גידול`).join('\n')}

## מדריכי טיפול ואילוף
${guides.map((g) => `- [${g.title}](${u(`/guides/${g.slug}`)}): ${g.excerpt}`).join('\n')}

## כלים חינמיים
- [מתאם הגזע](${u('/match')}): חידון שממליץ על גזע מתאים לפי אורח חיים
- [מחולל שמות לכלב](${u('/names')})
- [מחשבון עלות גידול כלב](${u('/calculator')})
- [מחשבון גיל הכלב בשנות אדם](${u('/dog-age')}): מותאם לגודל הגזע
- [מחשבון מנת מזון יומית](${u('/food-calculator')}): לפי נוסחת RER/MER
- [מרכז בריאות ועזרה ראשונה](${u('/health')})
- [מסלולי טיול לכלבים](${u('/walks')}): מסלולים אמיתיים ידידותיים לכלבים בישראל

## קהילות לפי עיר (${communities.length} ערים)
${communities.map((c) => `- [קהילת בעלי הכלבים ב${c.name}](${u(`/community/${c.slug}`)})`).join('\n')}

## הקהילה
- [קבוצת הפייסבוק של קהילה על ארבע](${u('/facebook')}): קהילת בעלי כלבים בישראל בפייסבוק - שאלות ותשובות, המלצות על וטרינרים ומאלפים לפי עיר, אזהרות בזמן אמת וחברים לטיול

## עוד באתר
- [כלב במצב חירום: מה עושים עכשיו](${u('/emergency')}): תשובות קצרות לכלב שאבד, הכשת נחש, חשש לכלבת, שוקולד, הקאות, מכת חום ואזעקות
- [מחולל מודעת כלב אבד](${u('/tools/lost-dog-poster')}): מודעה להדפסה ותמונה לשיתוף, נוצרת בדפדפן בלי שליחת פרטים
- [גינת כלבים קרובה אליי](${u('/near-me')}): גינות הכלבים הקרובות לפי מיקום, עם מרחק וניווט
- [מילון לבעלי כלבים](${u('/glossary')}): הגדרות קצרות לרישיון, שבב, מרכז הרישום, כלב מסוכן, חובת רצועה ועוד, עם מספרי הסעיפים בחוק
- [חידון חוקי הכלבים](${u('/quiz')}): עשר שאלות עם הסבר ומקור לכל תשובה
- [רשימות להדפסה](${u('/checklists')}): תיק חירום לכלב, ושבוע ראשון עם גור
- [תעודת זהות לכלב](${u('/tools/dog-id-card')}): כרטיס עם תמונה, מספר שבב וטלפון של הווטרינר
- [תזכורת חיסון ליומן](${u('/tools/vaccine-reminder')}): תזכורת ליומן שבועיים לפני החיסון הבא
- [מה חדש באתר](${u('/whats-new')}): רשימת העדכונים לפי תאריך
- [מפת גינות כלבים](${u('/map')})
- [ספריית עסקים לבעלי כלבים](${u('/businesses')})
`

  return new Response(body, {
    headers: { 'Content-Type': 'text/plain; charset=utf-8' },
  })
}
