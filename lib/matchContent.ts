const num = (n: number): string => HE_NUM[n] ?? String(n)
const numOf = (n: number): string => HE_NUM_CONSTRUCT[n] ?? String(n)

/* ──────────────── קבוצות גזעים ────────────────
   הנגזרות מ-breeds.ts מחושבות. הנגזרות מקבוצות פנימיות של
   matcher.ts (שאינן מיוצאות) נכתבות כאן כרשימת slug ומתורגמות
   לשמות דרך המאגר, כך שלפחות השמות לעולם לא מתיישנים.        */

const SMALL_SLUGS = breeds.filter((b) => b.size === 'קטן').map((b) => b.slug)
const NOT_KID_SLUGS = breeds.filter((b) => !b.goodWithKids).map((b) => b.slug)
const KID_COUNT = BREED_COUNT - NOT_KID_SLUGS.length
const CALM_SLUGS = breeds.filter((b) => b.energy <= 2).map((b) => b.slug)
const HIGH_ENERGY_SLUGS = breeds.filter((b) => b.energy === 5).map((b) => b.slug)

/* הרשימות הבאות נגזרות ישירות מהקבוצות של matcher.ts ומסוננות מול
   מאגר הגזעים. אין כאן שכפול ידני: אם קבוצה בקוד המנוע משתנה,
   הטקסט בעמוד משתנה איתה, ואי אפשר להגיע למצב שהעמוד מתאר חידון
   אחר מזה שרץ מעליו. הסינון מול breeds מסלק slug מת (למשל
   'cavalier' ו-'pug' שנמצאים במערך easy אך אינם במאגר) כדי שלא
   נספור לקורא גזעים שלא קיימים באתר. */

const inCatalog = (slug: string): boolean => breeds.some((b) => b.slug === slug)

/** גזעים ידידותיים לבעלים מתחילים, כפי שהמנוע מנקד אותם. */
const EASY_SLUGS: string[] = EASY_FOR_BEGINNERS.filter(inCatalog)

/** גזעים תובעניים, כפי שהמנוע מנקד אותם. */
const DEMANDING_SLUGS: string[] = DEMANDING_FOR_BEGINNERS.filter(inCatalog)

/** גזעים רגישים לחום הישראלי, כפי שהמנוע מנקד אותם. */
const HEAT_SENSITIVE_SLUGS: string[] = HEAT_SENSITIVE_LIST.filter(inCatalog)

/** גזעים עמידים יחסית בחום, כפי שהמנוע מנקד אותם. */
