export const BREED_COUNT = breeds.length

/* ──────────────── עזרי ניסוח ──────────────── */

/** שם תצוגה בפרוזה. "מעורב / כלאיים" נקרא רע באמצע משפט. */
const PROSE_NAME: Record<string, string> = { mixed: 'כלב מעורב' }

const nameOf = (slug: string): string =>
  PROSE_NAME[slug] ?? breeds.find((b) => b.slug === slug)?.name ?? slug

/** מחבר רשימת שמות למשפט עברי תקין: "א, ב וג". */
function joinHe(items: string[]): string {
  if (items.length === 0) return ''
  if (items.length === 1) return items[0]
  return `${items.slice(0, -1).join(', ')} ו${items[items.length - 1]}`
}

const listOf = (slugs: string[]): string => joinHe(slugs.map(nameOf))

/** מספרים במילים (זכר). לשימוש כשהמשפט זורם טוב יותר במילה מבספרה. */
