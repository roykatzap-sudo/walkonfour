export function buildSearchIndex(): SearchEntry[] {
  const out: SearchEntry[] = [...PAGES]
  for (const g of guides) {
    out.push({ t: g.title, d: g.excerpt.slice(0, 120), u: `/guides/${g.slug}`, k: 'מדריך', x: g.category })
  }
  for (const b of breeds) {
    out.push({
      t: b.name,
      d: `${b.group} · ${b.size} · ${b.temperament.join(', ')}`,
      u: hasArticle(b.slug) ? `/articles/${b.slug}` : `/breeds/${b.slug}`,
      k: 'גזע',
      x: b.en,
    })
  }
  for (const h of allCityHubs()) {
    out.push({
      t: `גינות כלבים ב${h.community.name}`,
      d: `${h.parks.length} גינות בעיר ובסביבה${h.vets.length ? `, ${h.vets.length} וטרינרים` : ''}`,
      u: `/city/${h.community.slug}`,
      k: 'עיר',
      x: `${h.community.name} ${h.community.district}`,
    })
  }
  for (const l of lawSpokes) {
    out.push({ t: l.title, d: l.description.slice(0, 120), u: `/laws/${l.slug}`, k: 'חוק' })
  }
  for (const g of glossary) {
    out.push({ t: g.term, d: g.def.slice(0, 120), u: `/glossary#${g.id}`, k: 'מושג', x: (g.also ?? []).join(' ') })
  }
  return out
}
