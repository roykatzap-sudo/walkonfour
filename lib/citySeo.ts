import type { Community } from './communities'

export type CityFaq = { q: string; a: string }

export type CitySeo = {
  /** תשובה קצרה - מופיעה מיד אחרי הכותרת. */
  quickAnswer: string
  faq: CityFaq[]
}

export type CityCounts = {
  parks: number
  /** כמה מהגינות מסומנות כמגודרות. */
  fenced: number
  walks: number
  vets: number
  petShops: number
}

export function buildCitySeo(community: Community, c: CityCounts): CitySeo {
  const name = community.name
  const parkWord = c.parks === 1 ? 'גינת כלבים אחת' : `${c.parks} גינות כלבים`
  const fencedClause = c.fenced > 0 ? `, ${c.fenced === 1 ? 'אחת מהן מסומנת כמגודרת' : `${c.fenced} מהן מסומנות כמגודרות`}` : ''
  const vetsClause = c.vets > 0 ? ` ${c.vets === 1 ? 'מרפאה וטרינרית אחת' : `${c.vets} מרפאות וטרינריות`} באזור מופיעות בהמשך העמוד.` : ''
  const walksClause = c.walks > 0 ? ` באזור יש גם ${c.walks === 1 ? 'מסלול טיול אחד' : `${c.walks} מסלולי טיול`} שמתאימים לכלבים.` : ''

  const quickAnswer =
    `ב${name} ובסביבה הקרובה ממופות ${parkWord}${fencedClause}. לכל גינה יש כפתור ניווט ישיר, ולרבות מהן גם הרחוב הקרוב.` +
    vetsClause +
    walksClause +
    ' הנתונים מבוססים על מפת OpenStreetMap ועל רשימות עירוניות, ואפשר לדווח על גינה חסרה בתחתית העמוד.'

  const faq: CityFaq[] = [
    {
      q: `כמה גינות כלבים יש ב${name}?`,
      a: `במפה שלנו מסומנות ${parkWord} ב${name} ובסביבה הקרובה${fencedClause}. ייתכן שיש גינות נוספות שעדיין לא מופו. אם אתם מכירים גינה שלא מופיעה, אפשר להוסיף אותה דרך הטופס בתחתית העמוד.`,
    },
    {
      q: `איפה מותר לשחרר כלב מהרצועה ב${name}?`,
      a: `לפי סעיף 11 לחוק להסדרת הפיקוח על כלבים, כלב שיוצא מהחצר חייב להיות מוחזק ברצועה בידי אדם שמסוגל לשלוט בו. ראש הרשות המקומית רשאי לקבוע אזורים ומועדים שבהם החובה לא חלה, ולכן את המקומות המותרים ב${name} בודקים באתר העירייה ובשילוט בכניסה לגינה.`,
    },
    {
      q: `אילו כללים חלים על בעלי כלבים ב${name}?`,
      a: `כללי היסוד זהים בכל הארץ: רישיון שנתי לכלב, שבב, חיסון כלבת, רצועה במרחב הציבורי ואיסוף צואה. חוקי העזר וגובה הקנסות משתנים מרשות לרשות, ולכן את הפרטים המדויקים כדאי לבדוק באתר של עיריית ${name}.`,
    },
    {
      q: `איפה יש וטרינר ב${name}?`,
      a:
        c.vets > 0
          ? `בעמוד הזה מופיעות ${c.vets === 1 ? 'מרפאה וטרינרית אחת' : `${c.vets} מרפאות וטרינריות`} ב${name} ובסביבה, עם כפתור ניווט, ולחלקן גם טלפון ושעות. הרשימה מבוססת על OpenStreetMap, היא לא מלאה ואינה המלצה. כדאי לשמור מראש את הטלפון של מרפאת חירום קרובה, ולא לחפש אותו ברגע האמת.`
          : `עדיין אין לנו רשימת מרפאות ל${name}. כדאי לשמור מראש את הטלפון של מרפאת חירום קרובה, ולא לחפש אותו ברגע האמת. מכירים מרפאה טובה? אפשר להציע אותה בתחתית העמוד.`,
    },
    {
      q: `מה חשוב לדעת על טיולים עם כלב ב${name} בקיץ?`,
      a: `בקיץ האספלט מתחמם מאוד ויש סכנה למכת חום. מטיילים בשעות הקרירות, מוקדם בבוקר ובערב, דואגים למים, ובודקים את המדרכה עם כף היד לפני שיוצאים. גינה עם צל עדיפה בהרבה על גינה חשופה.`,
    },
  ]

  return { quickAnswer, faq }
}
